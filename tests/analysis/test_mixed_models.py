"""Tests for the cross-classified one-vs-rest mixed model on realized
message-level corruption (revision Task 5.1).

All tests run on SIMULATED data built here, never on the real labeled/
exposure parquets (still being generated by a background job at the time
this task was implemented -- see the task brief's environment note).
"""
import numpy as np
import pandas as pd
import pytest

from idrift.analysis.mixed_models import build_analysis_frame, fit_multinomial

# ---------------------------------------------------------------------------
# Simulation ingredients for the headline recovery gate.
#
# 40 messages x 5-level CER grid x 3 replicates = 600 rows. Drift-vs-rest
# probability is generated from a KNOWN logistic model:
#
#   logit(P(drift)) = beta0 + beta_cer * realized_cer + 0.02 * n_errors
#                     + 0.001 * char_len + 0.3 * corrupted_negation
#                     + 0.3 * corrupted_numeral + fam_effect + msg_re[message]
#
# with beta_cer = 4.0 (KNOWN positive slope, the primary quantity under
# test), msg_re ~ N(0, SD_MSG_TRUE = 0.8) (KNOWN message-level random-
# intercept SD, the second quantity under test), and a fixed +/-0.4 shift
# between the two simulated model families. Non-drift rows are split
# faithful/degraded by an independent coin flip (irrelevant to the fitted
# model, just needed so all three one-vs-rest outcomes have some support).
#
# SIM_SEED=6 is a fixed constant (not tuned per test run): across a sweep of
# seeds 0-7 during development, seed 6 gave a representative recovery
# (drift-vs-rest realized_cer point estimate 4.11 against true 4.0, message
# SD point estimate 0.76 against true 0.8) rather than a best-case outlier,
# while every seed in that sweep passed the same coverage/sign assertions
# below.
# ---------------------------------------------------------------------------

SIM_SEED = 6
BETA0_TRUE = -2.2
BETA_CER_TRUE = 4.0
SD_MSG_TRUE = 0.8
N_MESSAGES = 40
CER_LEVELS = (0.0, 0.1, 0.2, 0.3, 0.4)
N_REP = 3
MODELS = ("gemma3:4b", "gemma3:27b", "qwen3:8b", "qwen3:32b")
CORPORA = ("AUTH", "CRIT")
_FAMILY_EFFECT = {"gemma3": -0.4, "qwen3": 0.4}


def _simulate(seed):
    rng = np.random.default_rng(seed)
    msg_re = rng.normal(0, SD_MSG_TRUE, N_MESSAGES)
    rows = []
    for mi in range(N_MESSAGES):
        message_id = f"msg_{mi:03d}"
        corpus = CORPORA[mi % 2]
        for cer in CER_LEVELS:
            for rep in range(N_REP):
                model_id = MODELS[rng.integers(len(MODELS))]
                family = model_id.split(":")[0]
                n_errors = int(rng.poisson(1 + 8 * cer))
                char_len = int(rng.integers(20, 120))
                corrupted_negation = int(rng.random() < 0.1)
                corrupted_numeral = int(rng.random() < 0.1)
                lin = (
                    BETA0_TRUE
                    + BETA_CER_TRUE * cer
                    + 0.02 * n_errors
                    + 0.001 * char_len
                    + 0.3 * corrupted_negation
                    + 0.3 * corrupted_numeral
                    + _FAMILY_EFFECT[family]
                    + msg_re[mi]
                )
                p_drift = 1 / (1 + np.exp(-lin))
                is_drift = rng.binomial(1, p_drift)
                if is_drift:
                    label = "drift"
                else:
                    label = "faithful" if rng.random() < 0.8 else "degraded"
                rows.append(
                    dict(
                        message_id=message_id,
                        replicate_idx=rep,
                        realized_cer=cer,
                        n_errors=n_errors,
                        char_len=char_len,
                        corrupted_negation=corrupted_negation,
                        corrupted_numeral=corrupted_numeral,
                        model_id=model_id,
                        family=family,
                        corpus=corpus,
                        label=label,
                    )
                )
    return pd.DataFrame(rows)


@pytest.fixture(scope="module")
def sim_df():
    return _simulate(SIM_SEED)


# ---------------------------------------------------------------------------
# 1. Simulated recovery (the gate).
# ---------------------------------------------------------------------------


def test_drift_slope_recovery_and_engine_documented(sim_df):
    result = fit_multinomial(sim_df, seed=0)

    assert set(result.keys()) == {"faithful", "degraded", "drift"}
    drift = result["drift"]
    assert drift["outcome"] == "drift"
    assert drift["engine"] in ("glmm_vb", "clustered_logit_fallback")
    assert drift["n_obs"] == len(sim_df)
    assert drift["n_groups"]["message_id"] == N_MESSAGES

    coef = drift["coefficients"]["realized_cer"]
    # (a) correct sign and CI coverage of the known true slope, regardless
    # of which engine fired.
    assert coef["est"] > 0
    assert coef["ci_lo"] <= BETA_CER_TRUE <= coef["ci_hi"]

    # (b) message-level variance component: only asserted for the primary
    # VB engine (the fallback explicitly reports variance components as
    # unavailable -- see its "notes" -- so there is nothing to recover
    # there; if the fallback fires in this environment, (a) above is the
    # full gate and that is expected/documented, not a test bug).
    if drift["engine"] == "glmm_vb":
        assert drift["converged"] is True
        msg_sd_est = drift["variance_components"]["message_id"]
        assert abs(msg_sd_est - SD_MSG_TRUE) < 0.4
    else:
        assert drift["variance_components"] == {}
        assert "unavailable" in drift["notes"]


def test_fallback_ladder_fires_when_primary_engine_raises(sim_df, monkeypatch):
    # The chosen SIM_SEED converges via the primary VB engine in this
    # environment (see test_drift_slope_recovery_and_engine_documented), so
    # the fallback ladder is never exercised end to end by that test alone.
    # Force the primary engine to fail here (independent of any real
    # numerical non-convergence) to verify the ladder itself: `notes` names
    # the fallback, `engine` reports it, and coefficients/CIs still come
    # back usable, with variance_components explicitly empty.
    import idrift.analysis.mixed_models as mm

    def _boom(data, seed):
        raise RuntimeError("forced failure for fallback-ladder test")

    monkeypatch.setattr(mm, "_fit_vb", _boom)
    result = fit_multinomial(sim_df, seed=0)

    drift = result["drift"]
    assert drift["engine"] == "clustered_logit_fallback"
    assert drift["variance_components"] == {}
    assert "FALLBACK LADDER FIRED" in drift["notes"]
    assert "forced failure for fallback-ladder test" in drift["notes"]
    coef = drift["coefficients"]["realized_cer"]
    assert coef["est"] > 0
    assert coef["ci_lo"] <= BETA_CER_TRUE <= coef["ci_hi"]


def test_degraded_and_faithful_fits_run_without_crashing(sim_df):
    result = fit_multinomial(sim_df, seed=0)
    for outcome in ("degraded", "faithful"):
        r = result[outcome]
        assert r["outcome"] == outcome
        assert r["engine"] in ("glmm_vb", "clustered_logit_fallback")
        assert "realized_cer" in r["coefficients"]
        assert np.isfinite(r["coefficients"]["realized_cer"]["est"])


# ---------------------------------------------------------------------------
# 2. Determinism.
# ---------------------------------------------------------------------------


def test_determinism_same_df_and_seed_reproduce_identical_coefficients(sim_df):
    result_a = fit_multinomial(sim_df, seed=0)
    result_b = fit_multinomial(sim_df, seed=0)

    assert result_a["drift"]["engine"] == result_b["drift"]["engine"]
    for outcome in ("faithful", "degraded", "drift"):
        ca = result_a[outcome]["coefficients"]
        cb = result_b[outcome]["coefficients"]
        assert ca.keys() == cb.keys()
        for name in ca:
            assert ca[name]["est"] == cb[name]["est"]
            assert ca[name]["se"] == cb[name]["se"]
        assert result_a[outcome]["variance_components"] == result_b[outcome]["variance_components"]


