def _labeled_fixture():
    return pd.DataFrame(
        {
            "message_id": ["m1", "m1", "m2", "m3"],
            "cer_target": [0.1, 0.2, 0.1, 0.1],
            "replicate_idx": [0, 0, 0, 0],
            "label": ["drift", "faithful", "degraded", "faithful"],
            "realized_cer": [0.09, 0.21, 0.11, 0.10],
            "model": ["gemma3:27b", "gemma3:27b", "qwen3:8b", "gemma3:27b"],
            "corpus": ["AUTH", "AUTH", "CRIT", "AUTH"],
        }
    )


def _exposure_fixture():
    # m3/cer_target=0.1/replicate_idx=0 deliberately has NO matching exposure
    # row, so the unmatched-labeled-row path is exercised for real.
    return pd.DataFrame(
        {
            "message_id": ["m1", "m1", "m2"],
            "corpus": ["AUTH", "AUTH", "CRIT"],
            "cer_target": [0.1, 0.2, 0.1],
            "replicate_idx": [0, 0, 0],
            "n_errors": [3, 5, 1],
            "corrupted_negation": [1, 0, 0],
            "corrupted_numeral": [0, 0, 1],
            "text": ["HELLO WORLD", "HELLO WORLD", "GOOD MORNING TO YOU"],
        }
    )


def test_build_analysis_frame_join_correctness_and_derivations():
    merged = build_analysis_frame(_labeled_fixture(), _exposure_fixture())

    # No row multiplication: exactly one output row per labeled input row.
    assert len(merged) == 4

    # Right predictor values land on the right rows (m1/cer=0.1 vs m1/cer=0.2
    # must not be swapped or averaged).
    row_m1_a = merged[(merged.message_id == "m1") & (merged.cer_target == 0.1)].iloc[0]
    row_m1_b = merged[(merged.message_id == "m1") & (merged.cer_target == 0.2)].iloc[0]
    row_m2 = merged[merged.message_id == "m2"].iloc[0]
    assert row_m1_a["n_errors"] == 3
    assert row_m1_a["corrupted_negation"] == 1
    assert row_m1_b["n_errors"] == 5
    assert row_m1_b["corrupted_negation"] == 0
    assert row_m2["n_errors"] == 1
    assert row_m2["corrupted_numeral"] == 1

    # char_len derived from exposure's `text` length (no literal char_len
    # column in the fixture).
    assert row_m1_a["char_len"] == len("HELLO WORLD")
    assert row_m2["char_len"] == len("GOOD MORNING TO YOU")

    # model -> model_id rename, family derived by stripping the ":size" tag.
    assert row_m1_a["model_id"] == "gemma3:27b"
    assert row_m1_a["family"] == "gemma3"
    assert row_m2["model_id"] == "qwen3:8b"
    assert row_m2["family"] == "qwen3"

    # labeled's own corpus survives untouched (no _x/_y collision column).
    assert row_m2["corpus"] == "CRIT"
    assert "corpus_x" not in merged.columns and "corpus_y" not in merged.columns

    # Unmatched handling is explicit: m3 has no exposure match -> NaN
    # attached columns, row still present (not dropped).
    row_m3 = merged[merged.message_id == "m3"].iloc[0]
    assert pd.isna(row_m3["n_errors"])
    assert pd.isna(row_m3["char_len"])
    assert row_m3["label"] == "faithful"  # labeled-side data untouched


def test_build_analysis_frame_respects_existing_char_len_column():
    exposure = _exposure_fixture()
    exposure["char_len"] = [999, 999, 999]  # literal column should win, not be recomputed
    merged = build_analysis_frame(_labeled_fixture(), exposure)
    assert (merged.loc[merged.message_id != "m3", "char_len"] == 999).all()


def test_build_analysis_frame_raises_on_missing_join_key():
    labeled = _labeled_fixture().drop(columns=["cer_target"])
    with pytest.raises(ValueError, match="join key"):
        build_analysis_frame(labeled, _exposure_fixture())
