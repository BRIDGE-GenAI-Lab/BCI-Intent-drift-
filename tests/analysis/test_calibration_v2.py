# ---------------------------------------------------------------------------
# 1. ECE on a rigged perfectly-calibrated set.
# ---------------------------------------------------------------------------


def test_ece_near_zero_on_perfectly_calibrated_set():
    # 10 confidence levels, each with exactly enough correct/incorrect
    # draws that the empirical accuracy in that bin equals the stated
    # confidence -- e.g. conf=0.3 -> 3/10 correct, conf=0.7 -> 7/10 correct.
    rng = np.random.default_rng(0)
    conf = []
    correct = []
    for level in np.arange(0.05, 1.0, 0.1):  # bin midpoints: .05,.15,...,.95
        n = 100
        n_correct = int(round(level * n))
        block = np.array([1] * n_correct + [0] * (n - n_correct))
        rng.shuffle(block)
        conf.extend([level] * n)
        correct.extend(block.tolist())
    conf = np.array(conf)
    correct = np.array(correct)

    result = ece(conf, correct, n_bins=10, scheme="equal_width")
    assert result < 0.02


def test_ece_rejects_out_of_range_confidence():
    conf = np.array([0.1, 0.5, 1.5])  # 1.5 is out of [0, 1] -- e.g. an
    # un-normalized 0-100 verbalized confidence slipping through.
    correct = np.array([1, 0, 1])
    with pytest.raises(ValueError, match=r"\[0, ?1\]"):
        ece(conf, correct)


def test_ece_rejects_negative_confidence():
    conf = np.array([-0.1, 0.5])
    correct = np.array([1, 0])
    with pytest.raises(ValueError, match=r"\[0, ?1\]"):
        ece(conf, correct)


