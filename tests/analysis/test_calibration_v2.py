def test_build_calibration_frame_derives_correct_and_rescales_confidence(tmp_path):
    raw = pd.DataFrame(
        {
            "message_id": ["m1", "m1", "m2", "m3"],
            "model": ["gemma3:27b", "gemma3:27b", "qwen3:8b", "gemma3:27b"],
            "label": ["faithful", "drift", "degraded", "faithful"],
            "confidence": [90.0, 40.0, 60.0, 100.0],
        }
    )
    path = tmp_path / "labeled_fixture.parquet"
    raw.to_parquet(path)

    out = build_calibration_frame(str(path))

    assert list(out["correct"]) == [True, False, False, True]
    assert out["confidence"].tolist() == pytest.approx([0.9, 0.4, 0.6, 1.0])
    # Original columns survive untouched.
    assert out["message_id"].tolist() == raw["message_id"].tolist()
    assert out["model"].tolist() == raw["model"].tolist()


def test_build_calibration_frame_output_is_valid_ece_input(tmp_path):
    raw = pd.DataFrame(
        {
            "message_id": ["m1", "m2", "m3", "m4"],
            "model": ["gemma3:27b"] * 4,
            "label": ["faithful", "faithful", "drift", "degraded"],
            "confidence": [80.0, 60.0, 30.0, 50.0],
        }
    )
    path = tmp_path / "labeled_fixture2.parquet"
    raw.to_parquet(path)

    out = build_calibration_frame(str(path))
    value = ece(out["confidence"].to_numpy(), out["correct"].to_numpy().astype(float), n_bins=4)
    assert np.isfinite(value)


