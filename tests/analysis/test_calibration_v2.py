def test_build_calibration_frame_drops_and_reports_nan_confidence(tmp_path):
    raw = pd.DataFrame(
        {
            "message_id": ["m1", "m2", "m3", "m4", "m5"],
            "model": ["gemma3:27b", "gemma3:27b", "qwen3:8b", "gemma3:27b", "qwen3:8b"],
            "label": ["faithful", "drift", "degraded", "faithful", "faithful"],
            # Rows 2 and 5 (index 1, 4) have a missing verbalized confidence.
            "confidence": [90.0, np.nan, 60.0, 100.0, np.nan],
        }
    )
    path = tmp_path / "labeled_fixture_nan.parquet"
    raw.to_parquet(path)

    out = build_calibration_frame(str(path))

    # The 2 NaN-confidence rows are dropped.
    assert len(out) == 3
    assert not out["confidence"].isna().any()
    # The dropped count is reported via .attrs and matches exactly.
    assert out.attrs["dropped_nan_confidence"] == 2
    # Surviving rows are unaffected (same values, in original relative order).
    assert out["message_id"].tolist() == ["m1", "m3", "m4"]
    assert out["confidence"].tolist() == pytest.approx([0.9, 0.6, 1.0])
    assert list(out["correct"]) == [True, False, True]


def test_check_conf_range_raises_on_nan_naming_count():
    conf = np.array([0.1, np.nan, 0.5, np.nan, 0.9])
    correct = np.array([1, 0, 1, 0, 1], dtype=float)
    with pytest.raises(ValueError, match="2"):
        ece(conf, correct)


def test_clean_frame_passes_through_build_and_per_model_calibration_unchanged(tmp_path):
    raw = pd.DataFrame(
        {
            "message_id": ["m1", "m2", "m3", "m4"],
            "model": ["gemma3:27b"] * 4,
            "label": ["faithful", "faithful", "drift", "degraded"],
            "confidence": [80.0, 60.0, 30.0, 50.0],
        }
    )
    path = tmp_path / "labeled_fixture_clean.parquet"
    raw.to_parquet(path)

    out = build_calibration_frame(str(path))

    # No rows dropped on a clean (no-NaN) frame -- the guard does not
    # false-trigger.
    assert out.attrs["dropped_nan_confidence"] == 0
    assert len(out) == len(raw)
    assert out["confidence"].tolist() == pytest.approx((raw["confidence"] / 100.0).tolist())

    # per_model_calibration runs to completion, untouched, on the clean
    # frame produced by build_calibration_frame.
    result = per_model_calibration(out, n_boot=50, seed=0)
    assert set(result.keys()) == {"gemma3:27b"}
    assert np.isfinite(result["gemma3:27b"]["ece"])
